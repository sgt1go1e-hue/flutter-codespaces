// アプリ全体で使う型定義

export interface Point {
  x: number
  y: number
}

// 配管セグメント（1本の直線区間）
// フェーズ2以降で管種・サイズ・継手などの属性を追加していく。
export interface Segment {
  id: string
  start: Point
  end: Point
  /** スナップ後のアイソメ角度（度）。0/30/90/150/210/270/330 のいずれか */
  angle: number

  // --- 以降はフェーズ2以降で使用する属性（フェーズ1では未設定） ---
  /** 管種コード（pipes.json の id） */
  pipeType?: string
  /** 呼び径（サイズコード） */
  size?: string
  /**
   * 芯々寸法（この直線区間の中心〜中心の実寸, mm）。ユーザーが手入力する。
   * アイソメ図は非スケールのため、線のピクセル長ではなくこの値を寸法計算に使う。
   */
  centerLength?: number
  /**
   * この区間の継手種類（fittings.json の id）。始点・終点で別々には持たず1つに統合。
   * 未設定なら継承ロジックと同様、分岐箇所は 'tee_equal'・それ以外は 'elbow90_long'(ロング標準) を実効値とする。
   */
  fitting?: string
  /**
   * 始点側／終点側で個別に指定するエルボ継手id（fittings.json の elbow系id）。
   * 短い「キック区間」（両端ともエルボ接続）で、始点側と終点側で異なる種類の
   * エルボ(例: 片側だけショート)を使う場合にだけ設定する。未設定の端は
   * 従来どおり fitting（無ければ自動判定）に従う。片方だけロング/ショートを
   * 変えたい、という用途のためのピンポイントな上書きなので、fitting のように
   * 両端へ一括適用はされない。
   */
  startFitting?: string
  endFitting?: string
  /**
   * レジューサー/径違いチーズの「相手径」呼び径コード。
   * 自分の size と合わせて大径_小径を決め、全長や芯ズレ計算に使う。
   */
  reducerSize?: string
  /** 偏心レジューサーの合わせ面。'top'=上面合わせ / 'bottom'=下面合わせ。必須選択。 */
  reducerAlign?: 'top' | 'bottom'
  /**
   * レジューサーで分割する前(継手からレジューサーの先まで)の全体寸法(mm)。
   * レジューサー配置時に元の区間の芯々/芯先寸法を凍結して保持する(この値自体は
   * 以後変わらない)。メイン側(継手〜レジューサー太い方)・先端側(レジューサー
   * 細い方〜先)のどちらか一方だけが入力されているとき、もう一方を
   * 「この値 − 入力済みの値 − レジューサー長さ(H)」で自動算出するために使う。
   * レジューサー区間(先端側, fitting=reducer_*)にのみ持たせる。
   */
  reducerSpanLength?: number
  /**
   * Y継手(45°Y・90°大曲りY)分岐ノードの本管側で、この区間が枝の直後(下流側=
   * near)か枝の手前(上流側=far)かを表す。Y継手は本管の両側が非対称(芯〜差込み
   * 面の距離が異なる)で幾何学的に自動判定できないため、本管側の区間ごとに
   * 明示選択させる。分岐側(枝)の区間では意味を持たない。
   */
  wyeRole?: 'near' | 'far'
  /**
   * レジューサーの面間寸法(H, mm)の手入力値。reducerLengths.ts のマスタ表に
   * 無いサイズ組み合わせのときだけ使う(手入力ダイアログで設定)。マスタに
   * 値があるときはこちらは無視され、常にマスタの値を優先する。
   */
  reducerLengthOverride?: number
  /** 接続方法（connections の id）。例: フランジ接合 'flange' */
  connection?: string
  /**
   * 塩ビ(VP)の継手シリーズ。'dv'=DV継手（排水用・勾配考慮が必要）/
   * 'ts'=TS継手（給水用）。管種がVPのときのみ意味を持つ。
   */
  vpSeries?: 'dv' | 'ts'
  /**
   * 排水勾配の分母(例: 100 なら「1/100勾配」)。SGP管またはVP+DV継手の
   * 区間にのみ設定できる。この区間の芯々寸法から生じる高低差
   * (centerLength / slopeDenom)を、上流側に隣接する縦区間(90°/270°)の
   * 寸法から自動的に差し引く（勾配で下がった分、縦区間が短くなる）。
   */
  slopeDenom?: number
  /**
   * 始点側 / 終点側のフランジ。
   * 'double'（両フランジ・途中挿入の接続面）/ 'single'（片フランジ・ルート終端のエンド用）。
   * 両フランジは配置時に前後セグメントへ分割され、その接合ノードの両側に付く。
   */
  startFlange?: 'double' | 'single'
  endFlange?: 'double' | 'single'

  /**
   * 直接の親（上流）セグメントの id。属性継承に使う。
   * pipeType / size が未設定のときは親をたどって値を継承する。
   * 描画時に、始点が接続している既存セグメントを自動で親に設定する。
   */
  parentId?: string

  /**
   * 相番(合番)の手動上書き番号。未設定なら配管の接続を辿った順(デフォルト
   * ルール)で自動採番された番号を使う。この値が設定されている区間は、
   * 自動採番のやり直しでも上書きされない（現場の組み立てやすい順への
   * 最終調整をユーザーが行えるようにするため）。相番表示自体のON/OFF/自動判定は
   * 図面全体の設定(defaults.assemblyNumberMode)で行う。
   */
  assemblyNumberOverride?: number

  /**
   * 現場溶接マーク(工場での加工分割点)。「ここから先は現場で溶接して繋ぐ」
   * ことを示す目印。継手ごとではなく、配管ライン上の特定の1箇所にのみ置く
   * (このセグメント上の1点として保持。1本のセグメントにつき最大1箇所)。
   * あくまで表示専用の注記であり、切り寸法等の計算結果には一切関与しない。
   */
  fieldWeldMark?: {
    /** セグメント上の位置(0=始点 ... 1=終点)。既存の継手ノードに置きたい場合は0か1を使う。 */
    t: number
    /** 三角マークの頂点の向き(タップ/ボタンで反転するトグル値。自動計算はしない) */
    flipped: boolean
    /**
     * マークをドラッグで移動した場合の、対象点(t位置)からの相対オフセット
     * (表示スケール=1のときのpx相当。実際の描画ではuiScale倍して使う)。
     * 未設定なら、対象点に近い既定位置(寸法線と反対側)へ自動配置する。
     */
    offsetX?: number
    offsetY?: number
  }
  /**
   * 現場合わせ区間(現場で寸法を合わせるため、あえて長めに加工している区間)
   * かどうか。ONの間、この区間を二重線で表示し、両端に向き変更可能な
   * 三角マークを置く。表示専用のフラグで、切り寸法等の計算結果には
   * 一切影響しない。
   */
  fieldFitAllowance?: boolean
  /** 現場合わせ区間の始点側三角マークの向き(タップ/ボタンで反転するトグル値) */
  fieldFitStartFlipped?: boolean
  /** 現場合わせ区間の終点側三角マークの向き(タップ/ボタンで反転するトグル値) */
  fieldFitEndFlipped?: boolean

  /**
   * 配管ライン色分け(系統)。data/lineColors.ts の固定パレットのid
   * ('c1'〜'c6')。色自体に系統の意味は決め打ちせず、実際の系統名は
   * フォルダ単位/図面単位の対応表(colorLabels)側で自由に設定する。
   * あくまで表示専用で、切り寸法等の計算結果には一切関与しない。
   */
  colorId?: string

  /**
   * 現合(現物合わせ)区間: 工場出荷時点では寸法が確定せず、現場で実測しながら
   * 切って合わせる区間であることを示す。ONの間、通常の芯々/切り寸法の
   * 2段表記の代わりに、概算寸法・修飾語を使った注記表示に切り替わる
   * (確定寸法と誤読されないようにするため)。既存の「現場合わせ区間」装飾
   * (fieldFitAllowance、二重線+三角マーク)とは独立した項目で併用できる。
   * あくまで表示専用のフラグで、切り寸法・BOM等の計算結果には一切関与
   * しない(centerLengthによる通常の計算はこのフラグに関係なく従来通り動く)。
   */
  isGenGou?: boolean
  /** 現合区間の概算寸法(mm)。手入力のみで自動計算はしない。未入力可。 */
  genGouDimension?: number
  /** 現合区間の修飾語(「現合」「約」「実測」等のプリセット、または自由入力)。 */
  genGouQualifier?: string
  /** 現合区間の補足メモ(自由入力)。キャンバス上ではアイコンをタップして確認する。 */
  genGouNote?: string
}

// 図面全体の状態
export interface DrawingState {
  segments: Segment[]
  /** 選択中のセグメント id（未選択は null） */
  selectedId: string | null
}
